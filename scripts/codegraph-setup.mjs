#!/usr/bin/env node
/**
 * Ensures CodeGraph git sync hooks are installed and the local `.codegraph/`
 * index is initialized and up to date. Safe to run in CI/serverless environments
 * where `codegraph` or `.git` may not be present (exits 0 gracefully).
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const ROOT_DIR = process.cwd();
const GIT_HOOKS_DIR = path.join(ROOT_DIR, ".git", "hooks");
const CODEGRAPH_DB = path.join(ROOT_DIR, ".codegraph", "codegraph.db");

const HOOK_START = "# >>> codegraph sync hook >>>";
const HOOK_END = "# <<< codegraph sync hook <<<";
const HOOK_NAMES = ["post-commit", "post-merge", "post-checkout"];

const HOOK_BLOCK = [
  HOOK_START,
  "# Auto-generated by codegraph. Removes cleanly with removeGitSyncHooks.",
  'export PATH="$HOME/.local/bin:$HOME/.codegraph/bin:$PATH"',
  "if command -v codegraph >/dev/null 2>&1; then",
  "  ( codegraph sync >/dev/null 2>&1 & ) >/dev/null 2>&1",
  "fi",
  HOOK_END,
].join("\n");

function installGitHooks() {
  if (!fs.existsSync(GIT_HOOKS_DIR)) return;

  for (const hookName of HOOK_NAMES) {
    const hookPath = path.join(GIT_HOOKS_DIR, hookName);
    let content = "";
    if (fs.existsSync(hookPath)) {
      content = fs.readFileSync(hookPath, "utf8");
    }

    if (content.includes(HOOK_START) && content.includes(HOOK_END)) {
      const startIdx = content.indexOf(HOOK_START);
      const endIdx = content.indexOf(HOOK_END) + HOOK_END.length;
      const updated =
        content.slice(0, startIdx) + HOOK_BLOCK + content.slice(endIdx);
      if (updated !== content) {
        fs.writeFileSync(hookPath, updated, { mode: 0o755 });
      }
      fs.chmodSync(hookPath, 0o755);
      continue;
    }

    if (!content.trim()) {
      fs.writeFileSync(hookPath, `#!/bin/sh\n\n${HOOK_BLOCK}\n`, {
        mode: 0o755,
      });
    } else {
      const sep = content.endsWith("\n") ? "\n" : "\n\n";
      fs.writeFileSync(hookPath, `${content}${sep}${HOOK_BLOCK}\n`, {
        mode: 0o755,
      });
    }
    fs.chmodSync(hookPath, 0o755);
  }
}

function resolveCodegraphBin() {
  const candidates = [
    path.join(os.homedir(), ".local", "bin", "codegraph"),
    path.join(os.homedir(), ".codegraph", "bin", "codegraph"),
  ];
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) return candidate;
  }
  try {
    return execFileSync("which", ["codegraph"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
}

function ensureIndexSynced() {
  const bin = resolveCodegraphBin();
  if (!bin) return;

  try {
    if (!fs.existsSync(CODEGRAPH_DB)) {
      execFileSync(bin, ["init", "--yes"], {
        cwd: ROOT_DIR,
        stdio: "ignore",
      });
    } else {
      execFileSync(bin, ["sync"], {
        cwd: ROOT_DIR,
        stdio: "ignore",
      });
    }
  } catch {
    // Non-fatal in postinstall/setup hooks
  }
}

installGitHooks();
ensureIndexSynced();
